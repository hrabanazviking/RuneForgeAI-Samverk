"""Digest job (S-235).

Part XI's weekly digest: an optional weekly letter
composed from S-221's canonical event store,
generated by a job -- off the request path. Before
this slice the pieces stood apart: S-227 could
queue notification email as a digest and S-228 let
a person choose a `weekly` cadence, but nothing
ever composed a digest of the week's *activity*;
the event store was read only as feeds (S-229) and
through the events API (S-231), both of which
answer requests. This module is the composer and
the job, under six laws:

- **Optional means the person's own recorded
  choice.** A digest is composed exactly for the
  accounts whose S-228 digest cadence is `weekly`
  -- the one opt-in the instance already records,
  read live from migration 92's
  `notification_preferences`. There is no second
  subscription record and no instance-wide blast:
  a person who never chose `weekly` is never
  composed for, and choosing another cadence
  stops future digests (standing digests are
  history and are not rewritten).
- **Composed from the event store, and only
  from it.** The job materialises the store
  through S-221's own `EventStore` (a compose
  syncs first, so a digest is never stale), then
  gathers the week's events in the pure
  `event_relevant` judgement: the recipient's own
  actions, and actions on repositories the
  recipient watches in a counted S-222 mode --
  `all` carries every event on the repository,
  `releases_only` carries its release events
  only, and `ignore` is a stored choice, not a
  watch, so it carries nothing. Every gathered
  event is then judged visible to the recipient
  by S-221's own visibility law, so a repository
  the recipient can no longer read contributes
  no row, no target, and no count -- S-209's
  rule, applied at compose time.
- **Generation is off the request path.** Nothing
  here is wired into the web server and no
  request ever composes a digest: `run_weekly`
  is the job (an operator or a scheduler runs
  it, e.g. `python3 -m samverk.digest_job
  <db-path> <repos-root>`), and every other face
  only reads standing digests. Composition is
  the job's work alone.
- **Exactly once per person per week.** The
  digest's week is a pure fact of the clock --
  `week_window` names the Monday-to-Monday UTC
  week a timestamp stands in, and the job
  composes the last *completed* week
  (`last_completed_week`) -- and migration 94's
  `weekly_digests` is UNIQUE on
  (account, week), so re-running the job for a
  week returns the standing digests and composes
  nothing twice. A week with nothing relevant is
  recorded honestly as `empty` and is never
  sent; it is still a record, so the job's
  answer for that week never changes.
- **The letter is composed once, at compose
  time.** The pure `compose_digest_letter` builds
  the plain-text letter from the gathered events
  -- oldest first, the order a week is lived in,
  each line saying who did what to what and
  when, under a subject that states the count --
  and the composed subject, body, and event ids
  are stored with the digest. What was sent is
  what the record says, word for word; a later
  permission change never rewrites a standing
  letter. Delivery rides a mailer seam in
  S-227's shape (a callable taking
  ``(address, subject, body)``): with no mailer
  the digest stands `composed` and nothing is
  sent; a transport failure leaves it `composed`,
  never raises into the job, and a later
  `send_digest` retries the standing letter --
  a digest marked `sent` was accepted by the
  transport exactly once.
- **Digests belong to their recipient.** Every
  read is scoped by the recipient's account id
  in the query itself; an anonymous caller is
  refused `authentication_required`, and a
  digest that is not the caller's is
  `digest_not_found`, exactly like one that
  does not exist. Renders say every state in
  plain words through S-010's escaping seam.

One migration: 94 creates `weekly_digests`
(schema 93 to 94). No new taxonomy event:
composing a digest witnesses no mutation -- it
reads the witness S-221 already keeps; 129
events stand.
"""

