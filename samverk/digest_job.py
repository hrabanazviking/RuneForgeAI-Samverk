WEEK_SECONDS = 7 * 24 * 60 * 60

# How many events one digest letter carries. A
# busier week is truncated at this cap and the
# letter says so in words, carrying the true
# total beside the shown count -- never a silent
# cut.
DIGEST_EVENT_LIMIT = 500

# What a digest gathers, said once, in words, and
# printed on the digest page: the scope is a
# labelled law, not a silent filter.
DIGEST_SCOPES = (
    "Your weekly digest gathers your own actions "
    "and actions in repositories you watch, from "
    "the event store, for one completed week. "
    "Repositories you cannot read never appear, "
    "not even as a count.")

Mailer = Callable[[str, str, str], None]


class DigestError(ValueError):
    def __init__(self, reason: str, message: str = ""):
        super().__init__(message or reason)
        self.reason = reason


def week_window(now: object) -> tuple[int, int]:
    """Pure: the (start, end) of the Monday-to-
    Monday UTC week *now* stands in -- start is
    Monday 00:00 UTC, end is the next Monday.
    Judged only from the timestamp, so the job,
    the record, and the battery all name the
    same week for the same moment."""
    ts = int(now)  # type: ignore[arg-type]
    days = ts // 86400
    weekday = (days + 3) % 7  # epoch day 0 was a Thursday
    start = (days - weekday) * 86400
    return (start, start + WEEK_SECONDS)


def last_completed_week(now: object) -> tuple[int, int]:
    """Pure: the most recent week that has wholly
    ended at *now* -- the week the job composes.
    A week still being lived in is never digested
    early."""
    start, _ = week_window(now)
    return (start - WEEK_SECONDS, start)


def event_relevant(event: CanonicalEvent, *,
                   recipient_id: int,
                   watch_modes: dict[str, str]) -> bool:
    """Pure: one event's relevance to one
    recipient, judged only from the event and
    the recipient's counted watch modes (full
    repository name -> mode). The recipient's
    own actions are always relevant; a watched
    repository's actions are relevant under its
    mode -- `all` carries everything,
    `releases_only` carries release events only;
    anything else (an unwatched repository, an
    `ignore` choice, a non-repository event by
    someone else) is not the recipient's week.
    Visibility is a separate judgement, applied
    by the composer through S-221's law."""
    if event.actor_id is not None and event.actor_id == recipient_id:
        return True
    repo = event.repository
    if repo is None:
        return False
    mode = {name.lower(): m for name, m in watch_modes.items()}.get(
        repo.lower())
    if mode == "all":
        return True
    if mode == "releases_only":
        return event.verb.startswith("repo.release.")
    return False


def _event_line(event: CanonicalEvent) -> str:
    actor = event.actor or event.actor_kind
    target = event.target_id or event.target_kind
    when = time.strftime("%Y-%m-%d %H:%M UTC",
                         time.gmtime(event.created_at))
    return f"{actor} - {event.verb} - {target} - {when}"


def compose_digest_letter(username: str, week_start: int,
                          week_end: int,
                          events, *, total: int | None = None,
                          ) -> tuple[str, str]:
    """Pure: one week's digest as one plain-text
    letter -- ``(subject, body)``. The events are
    listed oldest first, the order the week was
    lived in, each line saying who did what to
    what and when; the subject and the first line
    state the true count, and a truncated letter
    (more events than `DIGEST_EVENT_LIMIT`) says
    so in words. The body opens with the digest's
    scope, so the letter itself says what it
    gathered and what it never carries."""
    rows = list(events)
    shown = len(rows)
    true_total = shown if total is None else int(total)
    span = (f"{time.strftime('%Y-%m-%d', time.gmtime(week_start))}"
            f" to {time.strftime('%Y-%m-%d', time.gmtime(week_end))}")
    subject = (f"Samverk: your weekly digest -- "
               f"{true_total} event{'s' if true_total != 1 else ''}, "
               f"{span}")
    lines = [
        f"Your Samverk weekly digest for {span}: "
        f"{true_total} event{'s' if true_total != 1 else ''}.",
        "",
        DIGEST_SCOPES,
        "",
    ]
    for index, event in enumerate(rows, start=1):
        lines.append(f"{index}. {_event_line(event)}")
    if true_total > shown:
        lines += [
            "",
            f"Showing the first {shown} of {true_total} events; "
            "the rest are in the feeds on the instance.",
        ]
    lines += [
        "",
        "This digest was composed from the event store by the "
        "weekly digest job. It exists because your notification "
        "preferences choose a weekly digest; change the cadence "
        "there to stop future digests.",
    ]
    return (subject, "\n".join(lines) + "\n")


@dataclass(frozen=True)
class WeeklyDigest:
    """One person's digest of one week, as
    composed and stored: its window, its standing
    (composed / empty / sent), the event ids it
    gathered, and the letter composed from them,
    word for word."""
    id: int
    user_id: int
    username: str        # display case; '' when unknown
    week_start: int
    week_end: int
    status: str          # composed | empty | sent
    event_ids: tuple[int, ...]
    subject: str
    body: str
    created_at: int
    sent_at: int | None

    @property
    def event_count(self) -> int:
        return len(self.event_ids)

    @property
    def words(self) -> str:
        """The digest said in plain words -- its
        week, its count, and its standing, said
        outright."""
        span = (f"{time.strftime('%Y-%m-%d', time.gmtime(self.week_start))}"
                f" to {time.strftime('%Y-%m-%d', time.gmtime(self.week_end))}")
        if self.status == "empty":
            standing = "nothing to report, never sent"
        elif self.status == "sent":
            standing = "sent"
        else:
            standing = "composed, not yet sent"
        return (f"Weekly digest for {self.username or 'a recipient'} "
                f"({span}): {self.event_count} "
                f"event{'s' if self.event_count != 1 else ''} -- "
                f"{standing}.")


@dataclass(frozen=True)
class DigestRun:
    """One job run's honest account: the week it
    composed for, how many accounts were eligible
    (the `weekly` choice), and what the run did --
    newly composed, standing digests returned,
    empty weeks recorded, and letters sent."""
    week_start: int
    week_end: int
    eligible: int
    composed: int
    existing: int
    empty: int
    sent: int

    @property
    def words(self) -> str:
        span = (f"{time.strftime('%Y-%m-%d', time.gmtime(self.week_start))}"
                f" to {time.strftime('%Y-%m-%d', time.gmtime(self.week_end))}")
        return (f"Digest job for {span}: {self.eligible} "
                f"account(s) chose a weekly digest; "
                f"{self.composed} composed, {self.existing} "
                f"already standing, {self.empty} empty, "
                f"{self.sent} sent.")


class DigestJobStore:
    """The digest job and its records: eligibility
    from S-228's cadence table, composition from
    S-221's event store, standing digests in
    migration 94's `weekly_digests`, and delivery
    over an optional mailer seam in S-227's shape.

    ``mailer=None`` is the honest shape of an
    instance with no SMTP configured: digests are
    composed and stand recorded, and nothing is
    ever sent."""

    def __init__(
        self,
        conn: sqlite3.Connection,
        accounts: AccountStore,
        repositories: RepositoryStore,
        events: EventStore | None = None,
        preferences: NotificationPreferencesStore | None = None,
        mailer: Mailer | None = None,
        time_fn: Callable[[], float] = time.time,
    ):
        self._conn = conn
        self._accounts = accounts
        self._repos = repositories
        self._events = events or EventStore(conn, repositories, accounts)
        self._watches = WatchStarStore(conn, repositories, accounts)
        self._prefs = preferences
        self._mailer = mailer
        self._now = time_fn

    @property
    def smtp_configured(self) -> bool:
        return self._mailer is not None

    # -- eligibility -----------------------------------
    def eligible_users(self) -> list[User]:
        """Every account whose recorded S-228
        cadence is `weekly` -- the digest's whole
        subscription list, read live from the
        preference record itself. Accounts that
        no longer resolve are skipped, never
        composed for."""
        rows = self._conn.execute(
            "SELECT user_id FROM notification_preferences"
            " WHERE digest_cadence = 'weekly'"
            " ORDER BY user_id").fetchall()
        users: list[User] = []
        for row in rows:
            user = self._accounts.get_by_id(int(row["user_id"]))
            if user is not None:
                users.append(user)
        return users

    def _watch_modes(self, user_id: int) -> dict[str, str]:
        """The recipient's counted watches (full
        name -> mode), read live from S-222's
        rows: a repository they can no longer
        read still names a mode here, but its
        events are judged invisible at gather
        time, so nothing leaks."""
        rows = self._conn.execute(
            "SELECT repo_id, mode FROM repo_watches"
            " WHERE user_id = ?", (int(user_id),)).fetchall()
        modes: dict[str, str] = {}
        for row in rows:
            if row["mode"] not in COUNTED_WATCH_MODES:
                continue
            repo = self._repos.get_by_id(int(row["repo_id"]))
            if repo is not None:
                modes[repo.full_name] = row["mode"]
        return modes

    # -- composition -------------------------------------
    def gather_events(self, user: User, week_start: int,
                      week_end: int) -> list[CanonicalEvent]:
        """The recipient's week, gathered from the
        event store: materialised first (never
        stale), oldest first, each event judged
        relevant by the pure law and visible to
        the recipient by S-221's law. Repository
        names are matched in the case the witness
        recorded."""
        self._events.sync_all()
        modes = self._watch_modes(user.id)
        rows = self._conn.execute(
            "SELECT * FROM events"
            " WHERE created_at >= ? AND created_at < ?"
            " ORDER BY created_at, id",
            (int(week_start), int(week_end))).fetchall()
        gathered: list[CanonicalEvent] = []
        for row in rows:
            event = self._events._to_event(row)
            if not event_relevant(event, recipient_id=user.id,
                                  watch_modes=modes):
                continue
            if not self._events.visible_to(user, event):
                continue
            gathered.append(event)
        return gathered

    def compose_for(self, user: User, week_start: int,
                    week_end: int) -> tuple[WeeklyDigest, bool]:
        """Compose (or return) one recipient's
        digest of one week: ``(digest, created)``.
        A standing digest for the week is returned
        unchanged with `created` False -- the
        UNIQUE (account, week) record is the
        exactly-once law, and a digest is composed
        exactly once, from the store as it stood.
        An empty week is recorded `empty`. Commits
        before the answer."""
        if int(week_end) - int(week_start) != WEEK_SECONDS:
            raise DigestError(
                "week_invalid",
                "A digest covers exactly one week.")
        existing = self._standing(user.id, int(week_start))
        if existing is not None:
            return (existing, False)
        gathered = self.gather_events(user, int(week_start),
                                      int(week_end))
        total = len(gathered)
        shown = gathered[:DIGEST_EVENT_LIMIT]
        subject, body = compose_digest_letter(
            user.username, int(week_start), int(week_end),
            shown, total=total)
        status = "composed" if total else "empty"
        payload = json.dumps(
            [event_payload(e) for e in shown],
            sort_keys=True, separators=(",", ":"))
        now = int(self._now())
        with self._conn:  # commits before the answer
            cur = self._conn.execute(
                "INSERT OR IGNORE INTO weekly_digests"
                " (user_id, week_start, week_end, status,"
                " event_ids_json, events_json, subject, body,"
                " created_at, sent_at)"
                " VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, NULL)",
                (user.id, int(week_start), int(week_end), status,
                 json.dumps([e.id for e in shown],
                            separators=(",", ":")),
                 payload, subject, body, now))
            created = cur.rowcount > 0
        standing = self._standing(user.id, int(week_start))
        assert standing is not None
        return (standing, created)

    # -- the job -------------------------------------------
    def run_weekly(self, now: object = None,
                   ) -> DigestRun:
        """The job itself, off the request path:
        compose the last completed week's digest
        for every eligible account, then send each
        newly composed non-empty digest when a
        mailer is configured and the account has
        an address. Re-running composes nothing
        twice and sends nothing twice (a standing
        `sent` digest is never resent; a standing
        `composed` one is retried by `send_digest`,
        not by re-composition)."""
        moment = int(self._now()) if now is None else int(now)  # type: ignore[arg-type]
        week_start, week_end = last_completed_week(moment)
        users = self.eligible_users()
        composed = existing = empty = sent = 0
        for user in users:
            digest, created = self.compose_for(user, week_start,
                                               week_end)
            if not created:
                existing += 1
                continue
            if digest.status == "empty":
                empty += 1
                continue
            composed += 1
            if self.send_digest(user, digest.id):
                sent += 1
        return DigestRun(
            week_start=week_start, week_end=week_end,
            eligible=len(users), composed=composed,
            existing=existing, empty=empty, sent=sent)

    # -- delivery ------------------------------------------
    def send_digest(self, user: User | None,
                    digest_id: object) -> bool:
        """Send one standing digest's letter to its
        recipient: True exactly when this call sent
        it. Only the recipient may send their own
        digest; another account's digest is
        `digest_not_found`. An `empty` or already
        `sent` digest sends nothing and returns
        False; with no mailer or no address on the
        account nothing is sent and the digest
        stands `composed`. A transport failure is
        a False, never an exception -- the digest
        stands for a later retry. Commits before
        the answer."""
        holder = self._require_user(user)
        digest = self.get_digest(holder, digest_id)
        if digest.status != "composed":
            return False
        if self._mailer is None or not holder.email:
            return False
        try:
            self._mailer(holder.email, digest.subject, digest.body)
        except Exception:
            return False
        with self._conn:  # commits before the answer
            self._conn.execute(
                "UPDATE weekly_digests SET status = 'sent',"
                " sent_at = ? WHERE id = ? AND status = 'composed'",
                (int(self._now()), digest.id))
        return True

    # -- reads (recipients only) -----------------------------
    @staticmethod
    def _require_user(user: User | None) -> User:
        if user is None:
            raise DigestError(
                "authentication_required",
                "Sign in to see your weekly digests.")
        return user

    def _standing(self, user_id: int,
                  week_start: int) -> WeeklyDigest | None:
        row = self._conn.execute(
            "SELECT * FROM weekly_digests"
            " WHERE user_id = ? AND week_start = ?",
            (int(user_id), int(week_start))).fetchone()
        return self._to_digest(row) if row else None

    def digest_for_week(self, user: User | None, week_start: object,
                        ) -> WeeklyDigest | None:
        """The caller's own digest of one week, or
        None when the job has not composed one --
        an uncomposed week is a fact, not a
        refusal."""
        holder = self._require_user(user)
        if isinstance(week_start, bool) or not isinstance(week_start, int):
            return None
        return self._standing(holder.id, week_start)

    def get_digest(self, user: User | None,
                   digest_id: object) -> WeeklyDigest:
        """One of the caller's own digests by id:
        a digest that is not theirs is
        `digest_not_found`, exactly like one that
        does not exist -- digests belong to their
        recipient, and their existence is not
        leaked across accounts."""
        holder = self._require_user(user)
        if isinstance(digest_id, bool) or not isinstance(digest_id, int):
            raise DigestError("digest_not_found", "No such digest.")
        row = self._conn.execute(
            "SELECT * FROM weekly_digests"
            " WHERE id = ? AND user_id = ?",
            (int(digest_id), holder.id)).fetchone()
        if row is None:
            raise DigestError("digest_not_found", "No such digest.")
        return self._to_digest(row)

    def digests_for(self, user: User | None, *, limit: int = 52,
                    ) -> list[WeeklyDigest]:
        """The caller's own digests, newest week
        first. An anonymous caller is refused --
        digests belong to their recipient."""
        holder = self._require_user(user)
        clamped = max(1, min(int(limit), 500))
        rows = self._conn.execute(
            "SELECT * FROM weekly_digests WHERE user_id = ?"
            " ORDER BY week_start DESC, id DESC LIMIT ?",
            (holder.id, clamped)).fetchall()
        return [self._to_digest(r) for r in rows]

    # -- internals ------------------------------------------
    def _to_digest(self, row: sqlite3.Row) -> WeeklyDigest:
        try:
            ids = tuple(int(i) for i in
                        json.loads(row["event_ids_json"] or "[]"))
        except ValueError:
            ids = ()
        user = self._accounts.get_by_id(int(row["user_id"]))
        return WeeklyDigest(
            id=int(row["id"]), user_id=int(row["user_id"]),
            username=user.username if user else "",
            week_start=int(row["week_start"]),
            week_end=int(row["week_end"]), status=row["status"],
            event_ids=ids, subject=row["subject"], body=row["body"],
            created_at=int(row["created_at"]), sent_at=row["sent_at"])


# -- renders ---------------------------------------------------

def render_digest(digest: WeeklyDigest) -> str:
    """One digest's standing in plain words -- its
    week, its count, and whether it was sent, said
    outright."""
    return ('<li class="weekly-digest">'
            f"{escape_html_text(digest.words)}</li>")


def render_digest_page(digest: WeeklyDigest) -> str:
    """One digest as a page: its standing in
    words, its scope, and the letter exactly as
    composed -- the stored body, escaped through
    S-010's seam, so what the page shows is what
    was (or will be) sent."""
    lines = [
        "<h1>Weekly digest</h1>",
        f"<p>{escape_html_text(digest.words)}</p>",
        f"<p>{escape_html_text(DIGEST_SCOPES)}</p>",
        f"<h2>{escape_html_text(digest.subject)}</h2>",
        f"<pre>{escape_html_text(digest.body)}</pre>",
    ]
    return "\n".join(lines)


def render_digests_page(digests) -> str:
    """A recipient's digests in plain words. The
    empty state teaches the model in one screen:
    the digest is optional, is chosen as the
    weekly cadence on the notification preferences
    page, and is composed by the weekly job from
    the event store -- never on a request."""
    rows = list(digests)
    if not rows:
        return ('<p class="weekly-digests">No weekly digests yet. '
                "The weekly digest is optional: choose the weekly "
                "digest cadence on your notification preferences "
                "page, and the weekly digest job will compose one "
                "digest a week from the event store -- your own "
                "actions and actions in repositories you watch. "
                "Digests are generated by the job, never while "
                "you browse.</p>")
    items = "".join(render_digest(d) for d in rows)
    return f'<ul class="weekly-digests">{items}</ul>'


def main(argv: list[str] | None = None) -> int:
    """The job's command line, run by an operator
    or a scheduler -- the off-request-path entry:
    ``python3 -m samverk.digest_job <db-path>
    <repos-root>`` composes the last completed
    week's digests (no mailer: composition and
    recording only, delivery configured by the
    embedding operator) and prints the run's
    honest account."""
    from . import db
    args = list(sys.argv[1:] if argv is None else argv)
    if len(args) != 2:
        print("usage: python3 -m samverk.digest_job "
              "<db-path> <repos-root>")
        return 2
    conn = db.init_db(Path(args[0]))
    accounts = AccountStore(conn)
    repos = RepositoryStore(conn, Path(args[1]), accounts)
    store = DigestJobStore(conn, accounts, repos)
    run = store.run_weekly()
    print(run.words)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
